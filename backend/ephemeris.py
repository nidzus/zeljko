"""The astronomy layer. No interpretation happens here -- only computation.

Everything the advisor later says must trace back to a value produced in this
file. Nothing here is ever generated by a language model.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import swisseph as swe

# Moshier: analytical ephemeris built into the C library, no data files needed,
# accurate far beyond anything jyotisha distinguishes.
_BASE_FLAGS = swe.FLG_MOSEPH | swe.FLG_SPEED

SIGNS = [
    ("Mesha", "Aries"), ("Vrishabha", "Taurus"), ("Mithuna", "Gemini"),
    ("Karka", "Cancer"), ("Simha", "Leo"), ("Kanya", "Virgo"),
    ("Tula", "Libra"), ("Vrishchika", "Scorpio"), ("Dhanus", "Sagittarius"),
    ("Makara", "Capricorn"), ("Kumbha", "Aquarius"), ("Meena", "Pisces"),
]

NAKSHATRAS = [
    "Ashwini", "Bharani", "Krittika", "Rohini", "Mrigashira", "Ardra",
    "Punarvasu", "Pushya", "Ashlesha", "Magha", "Purva Phalguni",
    "Uttara Phalguni", "Hasta", "Chitra", "Swati", "Vishakha", "Anuradha",
    "Jyeshtha", "Mula", "Purva Ashadha", "Uttara Ashadha", "Shravana",
    "Dhanishta", "Shatabhisha", "Purva Bhadrapada", "Uttara Bhadrapada",
    "Revati",
]

# The nine grahas. Rahu and Ketu are the lunar nodes, not bodies -- Ketu is
# always exactly opposite Rahu, so we derive it rather than compute it.
GRAHAS = [
    ("Sun", "Surya", swe.SUN),
    ("Moon", "Chandra", swe.MOON),
    ("Mars", "Mangala", swe.MARS),
    ("Mercury", "Budha", swe.MERCURY),
    ("Jupiter", "Guru", swe.JUPITER),
    ("Venus", "Shukra", swe.VENUS),
    ("Saturn", "Shani", swe.SATURN),
    ("Rahu", "Rahu", swe.MEAN_NODE),
]

AYANAMSAS = {
    "LAHIRI": swe.SIDM_LAHIRI,
    "RAMAN": swe.SIDM_RAMAN,
    "KRISHNAMURTI": swe.SIDM_KRISHNAMURTI,
    "YUKTESHWAR": swe.SIDM_YUKTESHWAR,
}

NAKSHATRA_ARC = 360.0 / 27          # 13 deg 20'
PADA_ARC = NAKSHATRA_ARC / 4        # 3 deg 20'


def dms(degrees: float) -> str:
    d = int(degrees)
    m = int((degrees - d) * 60)
    s = ((degrees - d) * 60 - m) * 60
    return f"{d}\u00b0{m:02d}'{s:04.1f}\""


@dataclass
class Position:
    name: str
    sanskrit: str
    longitude: float          # sidereal, 0-360 along the zodiac
    speed: float              # degrees per day; negative means retrograde
    sign_index: int           # 0 = Mesha
    degrees_in_sign: float
    nakshatra_index: int
    pada: int
    house: int = 0            # filled in once the ascendant is known

    @property
    def sign(self) -> str:
        return SIGNS[self.sign_index][0]

    @property
    def sign_english(self) -> str:
        return SIGNS[self.sign_index][1]

    @property
    def nakshatra(self) -> str:
        return NAKSHATRAS[self.nakshatra_index]

    @property
    def retrograde(self) -> bool:
        # Rahu and Ketu are always retrograde by nature, which is not a
        # meaningful signal, so we report motion as computed and let the
        # interpretive layer decide what is worth mentioning.
        return self.speed < 0

    def __str__(self) -> str:
        r = " R" if self.retrograde else ""
        return (f"{self.name:<8} {dms(self.degrees_in_sign):>12} {self.sign:<11}"
                f" house {self.house:<3} {self.nakshatra} pada {self.pada}{r}")


@dataclass
class Chart:
    julian_day_ut: float
    latitude: float
    longitude: float
    ayanamsa_name: str
    ayanamsa_value: float
    ascendant: Position
    positions: list[Position] = field(default_factory=list)
    # The true midheaven, not simply ninety degrees from the ascendant. Needed
    # for directional strength, where the four angles are the reference points.
    midheaven: float = 0.0

    @property
    def lagna_sign_index(self) -> int:
        return self.ascendant.sign_index

    def house_of(self, sign_index: int) -> int:
        """Whole-sign houses: the lagna's whole sign is the 1st house."""
        return ((sign_index - self.lagna_sign_index) % 12) + 1

    def sign_in_house(self, house: int) -> int:
        return (self.lagna_sign_index + house - 1) % 12

    def get(self, name: str) -> Position:
        for p in self.positions:
            if p.name == name:
                return p
        raise KeyError(name)


def _decompose(name: str, sanskrit: str, longitude: float, speed: float) -> Position:
    longitude %= 360.0
    sign_index = int(longitude // 30)
    nak_index = int(longitude // NAKSHATRA_ARC)
    pada = int((longitude % NAKSHATRA_ARC) // PADA_ARC) + 1
    return Position(
        name=name,
        sanskrit=sanskrit,
        longitude=longitude,
        speed=speed,
        sign_index=sign_index,
        degrees_in_sign=longitude - sign_index * 30,
        nakshatra_index=nak_index,
        pada=pada,
    )


def compute_chart(
    julian_day_ut: float,
    latitude: float,
    longitude: float,
    ayanamsa: str = "LAHIRI",
) -> Chart:
    """Compute a sidereal rasi chart with whole-sign houses."""
    if ayanamsa not in AYANAMSAS:
        raise ValueError(f"Unknown ayanamsa {ayanamsa!r}; have {sorted(AYANAMSAS)}")
    swe.set_sid_mode(AYANAMSAS[ayanamsa])
    flags = _BASE_FLAGS | swe.FLG_SIDEREAL

    # Must use the _ex_ variant with the same flags, or the ayanamsa we report
    # will not match the positions we computed. See verify_ephemeris.py check 4.
    _, ayan_value = swe.get_ayanamsa_ex_ut(julian_day_ut, _BASE_FLAGS)

    # 'W' = whole sign houses, the standard bhava scheme in Parashari jyotisha:
    # the lagna's entire sign is the 1st house, so one sign is one house.
    _, ascmc = swe.houses_ex(julian_day_ut, latitude, longitude, b"W", swe.FLG_SIDEREAL)
    ascendant = _decompose("Lagna", "Lagna", ascmc[0], 0.0)
    midheaven = ascmc[1] % 360.0

    positions: list[Position] = []
    for name, sanskrit, body in GRAHAS:
        values, _ = swe.calc_ut(julian_day_ut, body, flags)
        positions.append(_decompose(name, sanskrit, values[0], values[3]))

    # Ketu sits exactly 180 degrees from Rahu, by definition.
    rahu = next(p for p in positions if p.name == "Rahu")
    positions.append(_decompose("Ketu", "Ketu", rahu.longitude + 180.0, rahu.speed))

    chart = Chart(
        julian_day_ut=julian_day_ut,
        latitude=latitude,
        longitude=longitude,
        ayanamsa_name=ayanamsa,
        ayanamsa_value=ayan_value,
        ascendant=ascendant,
        positions=positions,
        midheaven=midheaven,
    )
    ascendant.house = 1
    for p in chart.positions:
        p.house = chart.house_of(p.sign_index)
    return chart
